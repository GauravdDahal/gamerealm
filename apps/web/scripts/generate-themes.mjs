// Usage: node scripts/generate-themes.mjs   (from apps/web)
import { writeFileSync } from 'node:fs'
import { THEMES, DEFAULT_THEME } from '../src/lib/themes.mjs'

const hexToRgb = (h) => {
  const n = parseInt(h.slice(1), 16)
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}
const hslToHex = (h, s, l) => {
  s /= 100; l /= 100
  const k = (n) => (n + h / 30) % 12
  const a = s * Math.min(l, 1 - l)
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)))
  return '#' + [f(0), f(8), f(4)].map((x) => Math.round(x * 255).toString(16).padStart(2, '0')).join('')
}
const STOPS = { 50: 97, 100: 93, 200: 86, 300: 76, 400: 64, 500: 53, 600: 45, 700: 35, 800: 25, 900: 17, 950: 10 }
// gray scales are much darker/less saturated at the ends so panels stay moody
const GRAY_STOPS = { 50: 96, 100: 92, 200: 85, 300: 74, 400: 60, 500: 46, 600: 34, 700: 25, 800: 17, 900: 11, 950: 6 }

const block = (t) => {
  const out = []
  for (const [k, v] of Object.entries(t.tokens)) out.push(`  --c-${k}: ${hexToRgb(v).join(' ')};`)
  for (const [fam, [h, s]] of Object.entries(t.scales)) {
    const stops = fam === 'gray' ? GRAY_STOPS : STOPS
    for (const [step, l] of Object.entries(stops)) {
      const sat = fam === 'gray' ? s : Math.min(100, s)
      out.push(`  --color-${fam}-${step}: ${hslToHex(h, sat, l)};`)
    }
  }
  // families that share a palette with the theme's secondary / accent colours
  const alias = { indigo: 'purple', violet: 'purple', amber: 'orange', yellow: 'orange' }
  for (const [to, from] of Object.entries(alias))
    for (const step of Object.keys(STOPS)) out.push(`  --color-${to}-${step}: var(--color-${from}-${step});`)
  out.push(`  --theme-night: ${t.tokens.night};`)
  return out.join('\n')
}

let css = `/* GENERATED by scripts/generate-themes.mjs from src/lib/themes.mjs - do not edit by hand.
   Unlayered on purpose: it must win over Tailwind's layered :root palette. */\n\n`
for (const t of THEMES) {
  const sel = t.id === DEFAULT_THEME ? `html,\nhtml[data-theme="${t.id}"]` : `html[data-theme="${t.id}"]`
  css += `/* ${t.label} */\n${sel} {\n${block(t)}\n}\n\n`
}
writeFileSync(new URL('../src/app/themes.css', import.meta.url), css)
console.log('wrote themes.css for', THEMES.map((t) => t.id).join(', '))
